import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { loadConfig } from './config.js';
import { openDatabase } from './infrastructure/sqlite/database.js';
import { migrate } from './infrastructure/sqlite/migrate.js';
import { seedDevelopment } from './infrastructure/sqlite/seed.js';
import { createStores } from './infrastructure/sqlite/stores.js';
import { createProductAutomationService } from './application/product-automation.js';
import { createSourceIntake } from './application/source-intake.js';
import { createStudioQueries } from './application/studio-queries.js';
import { createExecutionKernel } from './modules/execution/execution-kernel.js';
import { createSourceService } from './modules/sources/source-service.js';
import { createPromptService } from './modules/prompts/prompt-service.js';
import { createServer } from './server.js';

const config = loadConfig();
mkdirSync(dirname(config.databasePath), { recursive: true });
const db = openDatabase(config.databasePath);
migrate(db);
seedDevelopment(db);
const stores = createStores(db);
const execution = createExecutionKernel({ db, stores });
const sourceService = createSourceService({ db, stores });
const sourceIntake = createSourceIntake({ db, stores });
const promptService = createPromptService({ db, stores });
const server = createServer({ stores, execution, sourceService, sourceIntake, promptService, automation: createProductAutomationService({ db, stores }), queries: createStudioQueries({ stores }), publicDir: new URL('../public/', import.meta.url), hostname: config.host, port: config.port });
console.log(JSON.stringify({ event: 'server_started', url: server.url.href, database: config.databasePath, runtime: `Bun ${Bun.version}`, mode: 'DEVELOPMENT' }));
const shutdown = () => { server.stop(true); db.close(); process.exit(0); };
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
